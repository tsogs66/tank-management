#!/usr/bin/env node
/**
 * Copy the server files the device runs into the web bundle.
 *
 * The phone executes the server's own routing rather than a second copy of it,
 * so those files have to be reachable as web assets. They are copied here at
 * build time rather than duplicated in the repository, so there is still one
 * of each to edit.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FILES = ['calc.js', 'bunker-live.js', 'index.js'];
/* Reference tables the routes read off disk: the density conversion table and
   the ISO 8217 fuel specifications. Without them the device answers 404 to
   three endpoints that work perfectly well on the server. */
const SEED = ['conversion.json', 'iso8217.json'];
const OUT = path.join(ROOT, 'public', 'embedded');

fs.mkdirSync(path.join(OUT, 'seed'), { recursive: true });
for (const file of FILES) {
  fs.copyFileSync(path.join(ROOT, 'server', file), path.join(OUT, file));
  console.log(`  server/${file} -> public/embedded/${file}`);
}
for (const file of SEED) {
  fs.copyFileSync(path.join(ROOT, 'seed', file), path.join(OUT, 'seed', file));
  console.log(`  seed/${file} -> public/embedded/seed/${file}`);
}
fs.writeFileSync(path.join(OUT, 'README.md'),
  'Generated by scripts/copy-embedded.js. Do not edit — change server/ instead.\n');
console.log(`${FILES.length + SEED.length} files copied.`);
